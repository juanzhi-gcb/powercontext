def aliases_for(title: str, task: str = "") -> list[str]:
    lowered = title.lower()
    matches = [(len(key), values) for key, values in TITLE_ALIASES.items() if key in lowered]
    if matches:
        return max(matches, key=lambda item: item[0])[1]
    if task in TASK_ALIASES:
        return TASK_ALIASES[task]
    return []


def has_cjk(text: str) -> bool:
    return any("\u4e00" <= character <= "\u9fff" for character in text)


def infer_task(query: str) -> str | None:
    if not has_cjk(query):
        return None
    lowered = query.lower()
    scores: dict[str, int] = {}
    for task, values in TASK_ALIASES.items():
        scores[task] = sum(1 for value in values if value.lower() in lowered)
    title_matches = [(len(key), key) for key in TITLE_ALIASES if key in lowered]
    if title_matches:
        _, key = max(title_matches)
        task = TITLE_TASKS[key]
        scores[task] = scores.get(task, 0) + sum(
            1 for value in TITLE_ALIASES[key] if value.lower() in lowered
        )
    task, score = max(scores.items(), key=lambda item: item[1])
    return task if score > 0 else None


def expand_query(query: str) -> str:
    if not has_cjk(query):
        return query
    lowered = query.lower()
    terms: list[str] = []
    for values in TASK_ALIASES.values():
        if any(value.lower() in lowered for value in values):
            terms.extend(values)
    title_matches = [
        (len(key), key)
        for key, values in TITLE_ALIASES.items()
        if key in lowered or any(value.lower() in lowered for value in values)
    ]
    if title_matches:
        _, key = max(title_matches)
        terms.extend(TITLE_ALIASES[key])
    if not terms:
        return query
    return " ".join([query, *dict.fromkeys(terms)])
